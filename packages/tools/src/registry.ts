export function getToolDefinition(toolId: string): ToolDefinition | null {
  return TOOL_REGISTRY.find((tool) => tool.id === toolId) ?? null;
}

export function isAvailableLocalRepoTool(toolId: string): boolean {
  const tool = getToolDefinition(toolId);
  return Boolean(
    tool &&
      tool.category === "local_repo" &&
      tool.executionState === "available" &&
      (tool.readOnly || tool.id === "file.apply_patch"),
  );
}
