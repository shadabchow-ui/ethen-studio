export function getMediaAppById(id: string): MediaAppDefinition | null {
  return MEDIA_APPS.find((app) => app.id === id) ?? null;
}

export function getMediaAppsByCategory(category: MediaAppCategory): MediaAppDefinition[] {
  if (category === "featured") {
    return MEDIA_APPS.filter((app) => app.storeCategories.includes("featured"));
  }
  return MEDIA_APPS.filter((app) => app.storeCategories.includes(category));
}

export function searchMediaApps(query: string): MediaAppDefinition[] {
  const lower = query.trim().toLowerCase();
  if (!lower) return MEDIA_APPS;

  return MEDIA_APPS.filter((app) => {
    const haystack = [
      app.title,
      app.description,
      app.category,
      app.archetype,
      ...app.requiredInputs,
      ...app.optionalInputs,
      ...app.outputTypes,
    ]
      .join(" ")
      .toLowerCase();

    return haystack.includes(lower);
  });
}

export function getFeaturedMediaApps(): MediaAppDefinition[] {
  return MEDIA_APPS.filter((app) => (app.flags ?? []).includes("featured"));
}

export function getMediaAppsBySection(sectionId: MediaAppSectionId): MediaAppDefinition[] {
  return MEDIA_APPS.filter((app) => app.storeSection === sectionId);
}

export function filterMediaApps(filters: {
  query?: string;
  category?: "all" | MediaAppCategory;
  section?: MediaAppSectionId;
}): MediaAppDefinition[] {
  const query = filters.query?.trim().toLowerCase() ?? "";

  return MEDIA_APPS.filter((app) => {
    if (filters.category && filters.category !== "all") {
      const categoryMatch =
        app.category === filters.category || app.storeCategories.includes(filters.category);
      if (!categoryMatch) return false;
    }

    if (filters.section && app.storeSection !== filters.section) {
      return false;
    }

    if (!query) return true;

    const haystack = [
      app.title,
      app.description,
      app.category,
      app.archetype,
      app.storeSection,
      ...app.requiredInputs,
      ...app.optionalInputs,
      ...app.outputTypes,
    ]
      .join(" ")
      .toLowerCase();

    return haystack.includes(query);
  });
}
